/**
 * The Sector Command welcome transmission, templated on the city name so the
 * player's chosen name appears in the tutorial dispatch instead of the
 * "MEGACITY JUAN" placeholder. createInitialState uses the placeholder
 * default; app/index.tsx confirmCharCreate rewrites the msg-welcome body via
 * this same function once the player has named the city, so the two can never
 * drift apart.
 */
export function buildWelcomeBody(cityName: string, originName?: string): string {
  const base = `City Commander, you have been appointed to command ${cityName}. The High Council expects order restored within the fiscal quarter. Failure is not an option. Your jurisdiction: 980,000+ citizens across 270 districts. Budgets are tight. Crime is rising. The factions are watching. Welcome to the seat of power.`;
  return originName
    ? `${base} Your ${originName} record arrived with the commission. The city will learn whether it was a qualification or a warning.`
    : base;
}

