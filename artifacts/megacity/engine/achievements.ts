export function checkAchievements(state: GameState): string[] {
  // Packaged release tampering is a runtime gate only. It does not modify or
  // permanently taint the save, so a repaired installation can earn again.
  if (!isReleaseIntegrityTrusted()) return [];
  // A save whose stored checksum failed verification on load was edited
  // outside the game (see markTampered in saveLoad.ts). It keeps playing
  // normally but earns no further achievements — quietly, with no banner.
  // Already-unlocked achievements are untouched. Note this is separate from
  // the in-game cheats feature, which is a designed system with its own
  // achievement and stays fully functional.
  if (state.integrityCompromised === true) return [];
  const unlocked = state.unlockedAchievements ?? [];
  const newlyUnlocked: string[] = [];
  const sdActive = isSixthDayActive(state.addons);
  const allAchs = sdActive ? [...ACHIEVEMENTS, ...SD_ACHIEVEMENTS_TYPED, ...BIOSPHERE_ACHIEVEMENTS, ...MEGA_PROJECT_ACHIEVEMENTS, ...ECOLOGY_ACHIEVEMENTS, ...META_ACHIEVEMENTS] : [...ACHIEVEMENTS, ...BIOSPHERE_ACHIEVEMENTS, ...MEGA_PROJECT_ACHIEVEMENTS, ...ECOLOGY_ACHIEVEMENTS, ...META_ACHIEVEMENTS];

  for (const ach of allAchs) {
    if (unlocked.includes(ach.id)) continue;
    try {
      if (ach.check(state)) {
        newlyUnlocked.push(ach.id);
      }
    } catch {
    }
  }

  return newlyUnlocked;
}

