export const TECH_MAP: Record<string, TechDef> = {};
for (const t of ALL_TECHNOLOGIES) {
  TECH_MAP[t.id] = t;
}

/**
 * Technologies a player may see or select. Story-arc technologies remain
 * event rewards: they are shown only after an event has unlocked them.
 * Keeping this alongside canResearch makes UI, actions, and auto-research
 * use one catalog/visibility contract.
 */
export function getVisibleTechnologies(
  addons?: Record<string, boolean>,
  unlocked: string[] = [],
): TechDef[] {
  const visible = [
    ...TECHNOLOGIES,
    ...RELIGION_TECHNOLOGIES,
    ...BIOSPHERE_TECHNOLOGIES,
    ...ECOLOGY_TECHNOLOGIES,
    ...STATECRAFT_SHADOW_TECHNOLOGIES,
  ];
  if (isSixthDayActive(addons)) visible.push(...SD_TECHNOLOGIES);
  if (isBigBrotherActive(addons)) visible.push(...BB_TECHNOLOGIES_TYPED);
  visible.push(...STORY_ARC_TECHNOLOGIES.filter((tech) => unlocked.includes(tech.id)));
  return visible;
}

export function canResearch(
  techId: string,
  unlocked: string[],
  addons?: Record<string, boolean>,
): { available: boolean; reason?: string } {
  const tech = TECH_MAP[techId];
  if (!tech) return { available: false, reason: "Technology not found" };
  if (!getVisibleTechnologies(addons, unlocked).some((candidate) => candidate.id === techId)) {
    return { available: false, reason: "Technology is not currently available" };
  }
  if (unlocked.includes(techId)) return { available: false, reason: "Already researched" };
  const missing = tech.prerequisites.filter((p) => !unlocked.includes(p));
  if (missing.length > 0) {
    const names = missing.map((m) => TECH_MAP[m]?.name ?? m).join(", ");
    return { available: false, reason: `Requires: ${names}` };
  }
  return { available: true };
}

export function getTotalTechEffects(unlocked: string[]): Record<string, number> {
  const totals: Record<string, number> = {};
  for (const id of unlocked) {
    const tech = TECH_MAP[id];
    if (!tech) continue;
    for (const [key, val] of Object.entries(tech.effects)) {
      totals[key] = (totals[key] ?? 0) + (val as number);
    }
  }
  return totals;
}
