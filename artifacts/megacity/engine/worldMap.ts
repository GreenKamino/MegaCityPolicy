/**
 * Megacity signals are visible on the strategic map even before the marshal
 * has charted the location. Discovery still controls route visibility and
 * interaction eligibility; this only answers whether a location gets a map
 * marker.
 */
export function isWorldLocationVisibleOnMap(location: WorldLocation, discoveredIds: string[]): boolean {
  if (isLegacyDeniedContentId(location.id)) return false;
  const discovered = Array.isArray(discoveredIds) ? discoveredIds : [];
  if (location.id === "cheyenne-mountain") return discovered.includes(location.id);
  return location.type === "megacity" || location.discovered || discovered.includes(location.id);
}

export function getWorldRoutes(discoveredIds: string[]): WorldRoute[] {
  const visible = new Set(
    WORLD_LOCATIONS
      .filter((l) => !isLegacyDeniedContentId(l.id) && (l.discovered || discoveredIds.includes(l.id)))
      .map((l) => l.id),
  );
  const routes: WorldRoute[] = [];
  const seen = new Set<string>();

  for (const loc of WORLD_LOCATIONS) {
    if (!visible.has(loc.id)) continue;
    for (const targetId of loc.connectedTo) {
      if (!visible.has(targetId)) continue;
      const key = [loc.id, targetId].sort().join("|");
      if (seen.has(key)) continue;
      seen.add(key);

      const target = WORLD_LOCATIONS.find((l) => l.id === targetId);
      let danger: WorldRoute["danger"] = "safe";
      if (loc.status === "hostile" || target?.status === "hostile") danger = "hostile";
      else if (loc.status === "undiscovered" || target?.status === "undiscovered") danger = "unknown";
      else if (loc.status === "neutral" || target?.status === "neutral") danger = "contested";

      routes.push({ from: loc.id, to: targetId, danger });
    }
  }
  return routes;
}

