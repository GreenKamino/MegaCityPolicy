// Per-channel caps for starting region bonuses. These are defensive bounds
// enforced at apply-time so designer data can never silently push a starting
// state past the intended "small head start" envelope. Credits are larger by
// nature than other resources (stockpiles are 50-100, treasury is 5000-class),
// so the credits cap is higher than the others. Cap applies to the SIGNED
// bonus value (i.e. abs(v) is clamped before it's added to state).
const BONUS_CAPS = {
  resourcesCredits: 5000,
  resourcesOther: 100,
  cityStats: 5,
  attributes: 2,
  skills: 2,
} as const;

function clampBonus(v: number, cap: number): number {
  if (v > cap) return cap;
  if (v < -cap) return -cap;
  return v;
}

// Subset of GameState that applyStartingBonus mutates. Keeping this narrow
// (instead of the full GameState) avoids a circular-import temptation between
// worldMap.ts and types.ts and documents exactly which slices the helper
// touches. Resources, cityStats, and player.* fields are intentionally typed
// as Record<string, number> so designer data can name new keys without a type
// gymnastic round-trip; the helper still guards `k in state.foo` at runtime.
type BonusTargetState = {
  resources?: Record<string, number>;
  buildings?: Record<string, number>;
  cityStats?: Record<string, number>;
  player?: {
    attributes?: Record<string, number>;
    skills?: Record<string, number>;
  };
};

// Applies a region's startingBonus to a freshly minted GameState in place.
// Caller is responsible for passing a state owned by them (typical use is the
// state object built by createInitialState() inside startNewGame). This is a
// pure mutation helper rather than a reducer because it sits in front of the
// rest of the start-of-run pipeline. Each per-channel value is clamped to the
// caps in BONUS_CAPS before being applied.
export function applyStartingBonus(state: BonusTargetState, region: StartingRegion): void {
  const bonus = region.startingBonus;
  if (!bonus) return;
  const resources = state.resources;
  if (bonus.resources && resources) {
    for (const [k, v] of Object.entries(bonus.resources)) {
      if (typeof v === "number" && k in resources) {
        const cap = k === "credits" ? BONUS_CAPS.resourcesCredits : BONUS_CAPS.resourcesOther;
        const boundedReserve = k === "food" || k === "steel" || k === "goods" ||
          k === "fuel" || k === "medSupplies" || k === "power";
        if (boundedReserve) {
          applyResourceDelta(
            { resources: resources as Resources, buildings: state.buildings ?? {} },
            k,
            clampBonus(v, cap),
          );
        } else {
          resources[k] = (resources[k] ?? 0) + clampBonus(v, cap);
        }
      }
    }
  }
  const cityStats = state.cityStats;
  if (bonus.cityStats && cityStats) {
    for (const [k, v] of Object.entries(bonus.cityStats)) {
      if (typeof v === "number" && k in cityStats) {
        cityStats[k] = (cityStats[k] ?? 0) + clampBonus(v, BONUS_CAPS.cityStats);
      }
    }
  }
  const attributes = state.player?.attributes;
  if (bonus.attributes && attributes) {
    for (const [k, v] of Object.entries(bonus.attributes)) {
      if (typeof v === "number" && k in attributes) {
        attributes[k] = (attributes[k] ?? 0) + clampBonus(v, BONUS_CAPS.attributes);
      }
    }
  }
  const skills = state.player?.skills;
  if (bonus.skills && skills) {
    for (const [k, v] of Object.entries(bonus.skills)) {
      if (typeof v === "number" && k in skills) {
        skills[k] = (skills[k] ?? 0) + clampBonus(v, BONUS_CAPS.skills);
      }
    }
  }
}

export function getRandomStartingRegion(): StartingRegion {
  return STARTING_REGIONS[Math.floor(Math.random() * STARTING_REGIONS.length)];
}

// Starting regions with access to a body of water (sea, lake, dam, etc.).
// Gates buildings that require water — naval dockyards, submarine bases,
// coastal defense batteries. Derived from the region's described geography:
//   western-coast      — shattered coastline, harbour settlements, ports
//   southern-depths    — crater lakes, overflow basin
//   northern-deadlands — mirror lake, dam of saints
//   pacific-foothold   — Pacific coastal shipping lanes
// All other starting regions are landlocked.
export const STARTING_REGIONS_WITH_WATER_ACCESS: ReadonlySet<string> = new Set([
  "western-coast",
  "southern-depths",
  "northern-deadlands",
  "pacific-foothold",
]);

export function hasCoastalAccess(regionId: string | undefined | null): boolean {
  if (!regionId) return false;
  return STARTING_REGIONS_WITH_WATER_ACCESS.has(regionId);
}
